#!/usr/bin/env python3
"""Generate libs/std/unicode_data.mu from Python's unicodedata.

The tables are simple code-point properties and simple one-to-one case mappings. Multi-character
case mappings (SpecialCasing: e.g. sharp s -> SS, Turkish dotted I) are intentionally not applied;
those belong to a full case-folding layer.

Run: python tools/gen-unicode-tables.py
"""
import sys
import unicodedata

OUT = "libs/std/unicode_data.mu"


def ranges(pred):
    out = []
    start = None
    prev = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok:
            if start is None:
                start = cp
            prev = cp
        else:
            if start is not None:
                out.append((start, prev))
                start = None
    if start is not None:
        out.append((start, prev))
    return out


def pairs(fn):
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        mapped = fn(ch)
        if len(mapped) == 1 and mapped != ch:
            out.append((cp, ord(mapped)))
    return out


def emit_array(f, name, values):
    f.write(f"const int[] {name} = {{\n")
    line = []
    for i, v in enumerate(values):
        line.append(f"0x{v:X}")
        if len(line) == 12:
            f.write("    " + ", ".join(line) + ",\n")
            line = []
    if line:
        f.write("    " + ", ".join(line) + ",\n")
    f.write("};\n\n")


def flatten(rs):
    out = []
    for a, b in rs:
        out.append(a)
        out.append(b)
    return out


def main():
    alpha = ranges(str.isalpha)
    digit = ranges(str.isdigit)
    space = ranges(str.isspace)
    upper = ranges(str.isupper)
    lower = ranges(str.islower)
    lower_pairs = pairs(str.lower)
    upper_pairs = pairs(str.upper)

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen-unicode-tables.py; do not edit.\n")
        f.write(f"// Unicode data version: {unicodedata.unidata_version}.\n")
        f.write("// Simple code-point properties and simple one-to-one case mappings only.\n\n")
        f.write("public unit std.unicode_data;\n\n")
        f.write("public bool is_alpha_cp(int cp) { return in_ranges(ALPHA, cp); }\n")
        f.write("public bool is_digit_cp(int cp) { return in_ranges(DIGIT, cp); }\n")
        f.write("public bool is_space_cp(int cp) { return in_ranges(SPACE, cp); }\n")
        f.write("public bool is_upper_cp(int cp) { return in_ranges(UPPER, cp); }\n")
        f.write("public bool is_lower_cp(int cp) { return in_ranges(LOWER, cp); }\n")
        f.write("public int lower_of(int cp) { return mapped(LOWER_FROM, LOWER_TO, cp); }\n")
        f.write("public int upper_of(int cp) { return mapped(UPPER_FROM, UPPER_TO, cp); }\n\n")
        f.write(
            "private bool in_ranges(const int[] ranges, int cp) {\n"
            "    isize lo = 0;\n"
            "    isize hi = ranges.length() / 2 - 1;\n"
            "    while lo <= hi {\n"
            "        isize mid = (lo + hi) / 2;\n"
            "        int a = ranges[mid * 2];\n"
            "        int b = ranges[mid * 2 + 1];\n"
            "        if cp < a { hi = mid - 1; }\n"
            "        else if cp > b { lo = mid + 1; }\n"
            "        else { return true; }\n"
            "    }\n"
            "    return false;\n"
            "}\n\n"
        )
        f.write(
            "private int mapped(const int[] from, const int[] to, int cp) {\n"
            "    isize lo = 0;\n"
            "    isize hi = from.length() - 1;\n"
            "    while lo <= hi {\n"
            "        isize mid = (lo + hi) / 2;\n"
            "        int a = from[mid];\n"
            "        if cp < a { hi = mid - 1; }\n"
            "        else if cp > a { lo = mid + 1; }\n"
            "        else { return to[mid]; }\n"
            "    }\n"
            "    return -1;\n"
            "}\n\n"
        )
        emit_array(f, "ALPHA", flatten(alpha))
        emit_array(f, "DIGIT", flatten(digit))
        emit_array(f, "SPACE", flatten(space))
        emit_array(f, "UPPER", flatten(upper))
        emit_array(f, "LOWER", flatten(lower))
        emit_array(f, "LOWER_FROM", [a for a, _ in lower_pairs])
        emit_array(f, "LOWER_TO", [b for _, b in lower_pairs])
        emit_array(f, "UPPER_FROM", [a for a, _ in upper_pairs])
        emit_array(f, "UPPER_TO", [b for _, b in upper_pairs])

    print(f"wrote {OUT}: alpha={len(alpha)} digit={len(digit)} space={len(space)} "
          f"upper={len(upper)} lower={len(lower)} lower_pairs={len(lower_pairs)} "
          f"upper_pairs={len(upper_pairs)} unicode={unicodedata.unidata_version}")


if __name__ == "__main__":
    sys.exit(main())
